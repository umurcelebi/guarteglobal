/* Application State */
let currentLang = 'en';
let currentSlideIndex = 0;
let heroInterval = null;

document.addEventListener('DOMContentLoaded', () => {
  initHeaderScroll();
  initLanguageDropdown();
  initHeroSlider();
  initMobileNav();
  initServiceCards();
  initLegalModals();
  initContactForm();

  // Check saved language or URL param
  const urlParams = new URLSearchParams(window.location.search);
  const langParam = urlParams.get('lang') === 'el' ? 'gr' : urlParams.get('lang');
  const rawSaved = localStorage.getItem('guarte_lang');
  const savedLang = rawSaved === 'el' ? 'gr' : rawSaved;
  if (langParam && I18N[langParam]) {
    setLanguage(langParam);
  } else if (savedLang && I18N[savedLang]) {
    setLanguage(savedLang);
  } else {
    setLanguage('en');
  }
});

/* Header Scroll Behavior & Active Section Spy */
function initHeaderScroll() {
  const header = document.getElementById('siteHeader');
  const navLinks = document.querySelectorAll('.nav-link');
  const sections = document.querySelectorAll('section[id]');

  window.addEventListener('scroll', () => {
    if (window.scrollY > 36) {
      header.classList.add('scrolled');
    } else {
      header.classList.remove('scrolled');
    }

    let currentSectionId = 'home';
    sections.forEach((sec) => {
      const top = sec.offsetTop - 140;
      if (window.scrollY >= top) {
        currentSectionId = sec.getAttribute('id');
      }
    });

    navLinks.forEach((link) => {
      link.classList.toggle('active', link.getAttribute('href') === `#${currentSectionId}`);
    });
  });
}

/* Mobile Menu */
function initMobileNav() {
  const btn = document.getElementById('mobileMenuBtn');
  const nav = document.getElementById('mainNav');
  if (!btn || !nav) return;

  btn.addEventListener('click', () => {
    nav.classList.toggle('mobile-open');
  });

  nav.querySelectorAll('a').forEach((a) => {
    a.addEventListener('click', () => {
      nav.classList.remove('mobile-open');
    });
  });
}

/* Language Switcher */
function initLanguageDropdown() {
  const dropdown = document.getElementById('langDropdown');
  const trigger = document.getElementById('langTrigger');
  const options = document.querySelectorAll('.lang-option');

  trigger.addEventListener('click', (e) => {
    e.stopPropagation();
    dropdown.classList.toggle('open');
  });

  options.forEach((opt) => {
    opt.addEventListener('click', () => {
      const lang = opt.getAttribute('data-lang');
      setLanguage(lang);
      dropdown.classList.remove('open');
    });
  });

  document.addEventListener('click', () => {
    dropdown.classList.remove('open');
  });
}

function setLanguage(lang) {
  if (lang === 'el') lang = 'gr';
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('guarte_lang', lang);
  document.documentElement.lang = lang === 'gr' ? 'el' : lang;

  const t = I18N[lang];
  document.title = t.metaTitle;

  // Update active state in dropdown
  document.getElementById('currentLangLabel').textContent = lang.toUpperCase();
  document.querySelectorAll('.lang-option').forEach((opt) => {
    opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
  });

  // Update simple data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const keyPath = el.getAttribute('data-i18n').split('.');
    let val = t;
    for (const k of keyPath) {
      if (val && val[k] !== undefined) val = val[k];
    }
    if (typeof val === 'string') {
      el.textContent = val;
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const keyPath = el.getAttribute('data-i18n-placeholder').split('.');
    let val = t;
    for (const k of keyPath) {
      if (val && val[k] !== undefined) val = val[k];
    }
    if (typeof val === 'string') {
      el.setAttribute('placeholder', val);
    }
  });

  // Render Hero Slide Copy
  renderHeroSlideCopy(currentSlideIndex);

  // Render Hero Aside List
  const asideListEl = document.getElementById('heroAsideList');
  if (asideListEl) {
    asideListEl.innerHTML = t.hero.asideList.map((w) => `<span>${w}</span>`).join('');
  }

  // Render Map Corridor Pills
  const corridorContainer = document.getElementById('mapCorridorPills');
  if (corridorContainer) {
    corridorContainer.innerHTML = t.about.corridors
      .map((c) => `<span class="corridor-pill">${c}</span>`)
      .join('');
  }

  // Render Wood Keywords
  const woodKeywordsEl = document.getElementById('woodKeywords');
  if (woodKeywordsEl) {
    woodKeywordsEl.innerHTML = t.about.woodKeywords.join('<br/>');
  }

  // Render Service Cards Copy
  t.services.cards.forEach((card, idx) => {
    const cardEl = document.querySelector(`.service-card[data-service-index="${idx}"]`);
    if (cardEl) {
      cardEl.querySelector('.service-title').textContent = card.title;
      cardEl.querySelector('.service-short').textContent = card.short;
      cardEl.querySelector('.service-learn-label').textContent = t.services.learnMore;
    }
  });

  // Render Division Tags
  ['d1Tags', 'd2Tags', 'd3Tags'].forEach((tagKey, idx) => {
    const container = document.getElementById(`divisionTags${idx + 1}`);
    if (container && Array.isArray(t.divisions[tagKey])) {
      container.innerHTML = t.divisions[tagKey]
        .map((tag) => `<span class="division-tag">${tag}</span>`)
        .join('');
    }
  });

  // Render Contact Form Select Options
  const selectEl = document.getElementById('inquiryDivision');
  if (selectEl) {
    selectEl.innerHTML = t.contact.formOptions
      .map((opt) => `<option value="${opt}">${opt}</option>`)
      .join('');
  }
}

/* Hero Slider Logic */
function initHeroSlider() {
  const tabs = document.querySelectorAll('.scene-tab');
  tabs.forEach((tab) => {
    tab.addEventListener('click', () => {
      const idx = parseInt(tab.getAttribute('data-slide'), 10);
      switchHeroSlide(idx);
      resetHeroTimer();
    });
  });

  resetHeroTimer();
}

function resetHeroTimer() {
  if (heroInterval) clearInterval(heroInterval);
  heroInterval = setInterval(() => {
    const nextIdx = (currentSlideIndex + 1) % 2;
    switchHeroSlide(nextIdx);
  }, 8000);
}

function switchHeroSlide(index) {
  currentSlideIndex = index;
  const bgs = document.querySelectorAll('.hero-slide-bg');
  const tabs = document.querySelectorAll('.scene-tab');

  bgs.forEach((bg, i) => {
    bg.classList.toggle('active', i === index);
  });

  tabs.forEach((tab, i) => {
    tab.classList.toggle('active', i === index);
  });

  renderHeroSlideCopy(index);
}

function renderHeroSlideCopy(index) {
  const t = I18N[currentLang];
  const slide = t.hero.slides[index] || t.hero.slides[0];

  const kickerEl = document.getElementById('heroKicker');
  const titleEl = document.getElementById('heroTitle');
  const descEl = document.getElementById('heroDescription');
  const coordsEl = document.getElementById('heroCoordsText');

  if (kickerEl) kickerEl.textContent = slide.kicker;
  if (titleEl) {
    titleEl.innerHTML = `${slide.titleLine1} <em>${slide.titleAccent}</em>`;
  }
  if (descEl) descEl.textContent = slide.desc;
  if (coordsEl) coordsEl.textContent = slide.coords;
}

/* Service Detail Modal */
function initServiceCards() {
  const cards = document.querySelectorAll('.service-card');
  cards.forEach((card) => {
    card.addEventListener('click', () => {
      const idx = parseInt(card.getAttribute('data-service-index'), 10);
      openServiceModal(idx);
    });
  });
}

function openServiceModal(index) {
  const t = I18N[currentLang];
  const card = t.services.cards[index];
  if (!card) return;

  const titleEl = document.getElementById('modalTitle');
  const bodyEl = document.getElementById('modalBody');

  titleEl.textContent = card.title;
  bodyEl.innerHTML = `
    <p style="font-size:0.78rem; font-weight:700; letter-spacing:0.14em; text-transform:uppercase; color:#a6823f; margin-bottom:0.6rem;">
      ${card.modalSubtitle}
    </p>
    <p>${card.modalDesc}</p>
    <ul>
      ${card.bullets.map((b) => `<li><span>${b}</span></li>`).join('')}
    </ul>
  `;

  openModal();
}

/* Legal Modals (Corporate Registry, Privacy, Terms) */
function initLegalModals() {
  const backdrop = document.getElementById('modalBackdrop');
  const closeBtn = document.getElementById('modalCloseBtn');

  document.querySelectorAll('[data-legal-modal]').forEach((btn) => {
    btn.addEventListener('click', () => {
      const type = btn.getAttribute('data-legal-modal');
      const lm = I18N[currentLang].legalModals;
      const titleEl = document.getElementById('modalTitle');
      const bodyEl = document.getElementById('modalBody');

      if (type === 'registry') {
        titleEl.textContent = lm.registryTitle;
        bodyEl.innerHTML = lm.registryBody;
      } else if (type === 'privacy') {
        titleEl.textContent = lm.privacyTitle;
        bodyEl.innerHTML = lm.privacyBody;
      } else if (type === 'terms') {
        titleEl.textContent = lm.termsTitle;
        bodyEl.innerHTML = lm.termsBody;
      }
      openModal();
    });
  });

  if (closeBtn) {
    closeBtn.addEventListener('click', closeModal);
  }
  if (backdrop) {
    backdrop.addEventListener('click', (e) => {
      if (e.target === backdrop) closeModal();
    });
  }
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeModal();
  });
}

function openModal() {
  const backdrop = document.getElementById('modalBackdrop');
  if (backdrop) backdrop.classList.add('open');
}

function closeModal() {
  const backdrop = document.getElementById('modalBackdrop');
  if (backdrop) backdrop.classList.remove('open');
}

/* Contact Inquiry Form */
function initContactForm() {
  const form = document.getElementById('contactForm');
  const feedback = document.getElementById('formFeedback');
  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const name = document.getElementById('inquiryName').value.trim();
    const email = document.getElementById('inquiryEmail').value.trim();
    const division = document.getElementById('inquiryDivision').value;
    const message = document.getElementById('inquiryMessage').value.trim();

    const t = I18N[currentLang];
    feedback.textContent = t.contact.formSuccess;
    feedback.classList.add('visible');

    const subject = encodeURIComponent(`[Guarte Global Inquiry] ${division} - ${name}`);
    const body = encodeURIComponent(
      `Sender / Company: ${name}\nEmail: ${email}\nDepartment: ${division}\n\nInquiry Details:\n${message}`
    );

    setTimeout(() => {
      window.location.href = `mailto:info@guarteglobal.com?subject=${subject}&body=${body}`;
    }, 600);
  });
}
